/**
 * Dynamically computes matching percentage and identifies matched skills
 * between the extracted resume text and each job opportunity.
 */
export function calculateJobMatches(
  resumeText: string,
  jobsList: JobOpportunity[] = INITIAL_JOBS
): JobOpportunity[] {
  if (!resumeText || resumeText.trim().length === 0) {
    return jobsList;
  }

  const normalizedResume = resumeText.toLowerCase();

  return jobsList
    .map((job) => {
      // Check which required skills are mentioned in the resume
      const matched = job.requiredSkills.filter((skill) => {
        const skillLower = skill.toLowerCase();
        // Exact word boundary or clean substring match
        const regex = new RegExp(`\\b${escapeRegExp(skillLower)}\\b`, 'i');
        return regex.test(normalizedResume) || normalizedResume.includes(skillLower);
      });

      const skillMatchRatio = matched.length / job.requiredSkills.length;

      // Base weight from skill matching (up to 70 points)
      let calculatedScore = Math.round(skillMatchRatio * 70);

      // Title affinity bonus (up to 20 points)
      const titleWords = job.title
        .toLowerCase()
        .split(/\s+/)
        .filter((w) => w.length > 3 && !['with', 'that', 'from', 'lead', 'senior'].includes(w));
      const hasTitleOverlap = titleWords.some((w) => normalizedResume.includes(w));
      if (hasTitleOverlap) {
        calculatedScore += 18;
      }

      // Experience & general keywords bonus (up to 12 points)
      if (
        normalizedResume.includes('experience') ||
        normalizedResume.includes('engineer') ||
        normalizedResume.includes('developer')
      ) {
        calculatedScore += 10;
      }

      // Clamp between 60% and 98%
      const finalScore = Math.min(98, Math.max(62, calculatedScore));

      return {
        ...job,
        matchPercentage: finalScore,
        matchedSkills: matched,
      };
    })
    .sort((a, b) => b.matchPercentage - a.matchPercentage);
}

function escapeRegExp(string: string): string {
  return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
